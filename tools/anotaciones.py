def trio(b):
    """El reparto con el que corre el codigo del banco b (tools/paginas.py)."""
    if b == 0:
        return {}
    t = 3 * ((b - 1) // 3) + 1
    return {0x6000: t, 0x8000: t + 1, 0xA000: t + 2}


